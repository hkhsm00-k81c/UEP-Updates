const fs=require('fs'),path=require('path');
const root=process.argv[2]||'app';
const g=fs.readFileSync(path.join(root,'resources','app','gyomuon.js'),'utf8');
const m=fs.readFileSync(path.join(root,'resources','app','electron','main.cjs'),'utf8');
const gd=fs.readFileSync(path.join(root,'resources','app','electron','google-data.cjs'),'utf8');
const p=JSON.parse(fs.readFileSync(path.join(root,'resources','app','package.json'),'utf8'));
const must=(v,msg)=>{if(!v)throw new Error(msg)};
must(/APP_VERSION\s*=\s*["']0\.82\.47["']/.test(g),'APP_VERSION 0.82.47 missing');
must(p.version==='0.82.47','package version mismatch');
must(g.includes('UEP_08247_SOURCE_DRIVEN_ADMISSIONS'),'source-driven marker missing');
must(g.includes("visibleAdmissions=admissions.filter(r=>String(r['UEP노출']||'Y').trim().toUpperCase()!=='N')"),'UEP visibility gate missing');
must(!g.includes("raw.includes('·')?raw.split('·')"),'middle-dot heuristic still present');
must(!g.includes("raw.split('·').map"),'middle-dot split still present');
must(g.includes("const name=String(r['전형명']||r['전형유형']||r['대전형']||'전형명 확인').trim()"),'one-row-one-card name source missing');
must(g.includes('setTimeout(uep08221ShowReleaseNotes,900)'),'shared release notes boot not restored');
must(g.includes('새 버전 수정사항 팝업을 공통 1회 표시 로직으로 복구했습니다.'),'0.82.47 release notes missing');
must(m.includes('admissionMinimumRows'),'raw minimum detail model missing in main');
must(gd.includes('admissionMinimums'),'normalized minimum model missing in google-data');
must(g.includes("dashboardAdmissionRows('admissionMinimumRows','54_수능최저DB')"),'Today University raw minimum model not used');
must(g.includes('UEP_08245_ADAPTIVE'),'two-column adaptive layout marker missing');
console.log('UEP 0.82.47 validation PASS');
