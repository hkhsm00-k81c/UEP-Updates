const fs=require('fs');
const path=require('path');
const root=path.resolve(process.argv[2]||'.');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const renderer=fs.readFileSync(path.join(root,'gyomuon.js'),'utf8');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
function must(c,m){if(!c)throw new Error(m);}
must(pkg.version==='0.82.90','package version must be 0.82.90');
must(renderer.includes('const APP_VERSION="0.82.90"; /* UEP_08290_BOARD_EXAM_MODE_UI */'),'runtime version marker missing');
must(renderer.includes('boardAdminUiAllowed()'),'admin-only UI guard missing');
must(renderer.includes('data-board-tool="exam"') && renderer.includes('시험모드'),'exam mode card/panel missing');
must(!renderer.includes('data-board-tool="message"'),'legacy screen-message tool still present');
must(renderer.includes('내신 지필고사') && renderer.includes('모의고사') && renderer.includes('기타 시험'),'exam type options missing');
must(renderer.includes('전체 시간표') && renderer.includes('현재 교시 중심') && renderer.includes('현재 + 전체 분할'),'exam layout options missing');
must(renderer.includes('숫자만 표시') && renderer.includes('미확인 인원 포함') && renderer.includes('숨김'),'attendance display options missing');
must(renderer.includes('시험문제 긴급 공지'),'urgent exam notice missing');
must(renderer.includes('시간별 화면 변화') && renderer.includes('종료 10분 전') && renderer.includes('쉬는 시간'),'exam phase editor missing');
must(renderer.includes('시험모드 적용 준비 중') && renderer.includes('시험모드 해제 준비 중'),'safe disabled write buttons missing');
must(renderer.includes('특별실'),'special room target missing');
for(let g=1;g<=3;g++)for(let c=1;c<=9;c++)must(renderer.includes(`${g}학년 ${c}반`),`class option missing ${g}-${c}`);
must(renderer.includes('장소<input type="text" placeholder="변경 장소"'),'timetable place field missing');
must(renderer.includes('사유 <small>선택</small>') && renderer.includes('미작성 가능'),'optional reason guidance missing');
must(renderer.includes('텍스트 ✓') && renderer.includes('링크 · 준비 중') && renderer.includes('이미지 · 준비 중') && renderer.includes('유튜브 · 준비 중'),'notice format support guidance missing');
must(index.includes('id="uep-08290-exam-mode-style"'),'exam mode CSS missing');
must(renderer.includes('UEP_BOARD_API_URL=') && renderer.includes('UEP_BOARD_DB_URL='),'Board live connection missing');
for(const marker of ['dashboard','students','attendance','grades','admissions','records','programs','timetable','settings'])must(renderer.includes(marker),`existing feature marker missing: ${marker}`);
const block=renderer.slice(renderer.indexOf('const UEP_BOARD_API_URL='),renderer.indexOf('function render(page)'));
must(!block.includes('MutationObserver'),'Board feature must not use MutationObserver');
must(!block.includes('document.addEventListener("click"'),'Board feature must not add global click interception');
console.log('UEP 0.82.90 Board exam mode UI regression OK');
