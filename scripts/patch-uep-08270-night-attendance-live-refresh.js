const fs=require('fs');
const path=require('path');
const root=process.argv[2]||'app/resources/app';
const gp=path.join(root,'gyomuon.js');
const mp=path.join(root,'electron','main.cjs');
const pp=path.join(root,'package.json');
const must=(ok,msg)=>{if(!ok)throw new Error(msg)};
let g=fs.readFileSync(gp,'utf8');
let m=fs.readFileSync(mp,'utf8');
must(/const\s+APP_VERSION\s*=\s*["']0\.82\.69["'];/.test(g),'expected 0.82.69 renderer base');
g=g.replace(/const\s+APP_VERSION\s*=\s*["']0\.82\.69["'];/,'const APP_VERSION = "0.82.70";');
g=g.replace(/const CURRENT='0\.82\.69';/g,"const CURRENT='0.82.70';");
const fnStart=m.indexOf('async function fetchOperationalData(');
const fnEnd=m.indexOf('\nasync function fetchLiveData(',fnStart);
must(fnStart>=0&&fnEnd>fnStart,'fetchOperationalData function missing');
let fn=m.slice(fnStart,fnEnd);
must(fn.includes('const result=await readSheetBatch(token,UEP_SPREADSHEET_ID,operationalEntries.map(([,range])=>range));'),'operational batch read missing');
must(fn.includes('const partial=parseGoogleSheetData(matrices);'),'operational parser missing');
must(fn.includes('nightSupervisors:partial.nightSupervisors||[]'),'operational patch object missing');
fn=fn.replace('const result=await readSheetBatch(token,UEP_SPREADSHEET_ID,operationalEntries.map(([,range])=>range));',`const [result,nightResult]=await Promise.all([\n    readSheetBatch(token,UEP_SPREADSHEET_ID,operationalEntries.map(([,range])=>range)),\n    // 0.82.70: 실행 중 추가·사후보정되는 야자출결을 운영 동기화에서 함께 갱신합니다.\n    // 열린 범위는 실제 사용행만 반환하므로 고정 대용량 행 범위를 만들지 않습니다.\n    readSheetBatch(token,UEP_PROCESSING_SPREADSHEET_ID,[\"'30_야자출결_정규화'!A:U\"])\n  ]);`);
fn=fn.replace('const partial=parseGoogleSheetData(matrices);',`matrices['30_야자출결_정규화']=nightResult?.[0]?.values||[];\n  const partial=parseGoogleSheetData(matrices);`);
fn=fn.replace('nightSupervisors:partial.nightSupervisors||[]','nightSupervisors:partial.nightSupervisors||[],nightAttendance:partial.nightAttendance||[]');
m=m.slice(0,fnStart)+fn+m.slice(fnEnd);
if(fs.existsSync(pp)){
  const p=JSON.parse(fs.readFileSync(pp,'utf8'));
  must(String(p.version)==='0.82.69','expected package 0.82.69');
  p.version='0.82.70';
  fs.writeFileSync(pp,JSON.stringify(p,null,2)+'\n','utf8');
}
fs.writeFileSync(gp,g,'utf8');
fs.writeFileSync(mp,m,'utf8');
console.log('UEP 0.82.70 night attendance live refresh patch applied');
