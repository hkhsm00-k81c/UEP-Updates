const fs=require('fs'),path=require('path');
const root=process.argv[2]||'app/resources/app';
const must=(v,m)=>{if(!v)throw new Error(m)};
const g=fs.readFileSync(path.join(root,'gyomuon.js'),'utf8');
const m=fs.readFileSync(path.join(root,'electron/main.cjs'),'utf8');
const p=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
must(/APP_VERSION\s*=\s*["']0\.82\.60["']/.test(g),'app version 0.82.60 missing');
must(p.version==='0.82.60','package version 0.82.60 missing');
must(g.includes("const CURRENT='0.82.60';"),'visible/current version 0.82.60 missing');
must(m.includes('const UEP_ADMISSIONS_SPREADSHEET_ID = "1BHSdaUbOhp9p_9RB0XGgrfOo4wS_Z8Up0ocSCAMYIIk";'),'new admissions spreadsheet id missing');
must(m.includes('const UEP_ADMISSIONS_FALLBACK_SPREADSHEET_ID = "1bphoIQ11E2qsc3ksOqrXuO7xqS4CFyH8Dagbld7A1hg";'),'basic-info fallback id missing');
must(m.includes('schoolReadBatchRead(UEP_ADMISSIONS_SPREADSHEET_ID'),'new admissions School Read primary missing');
must(m.includes('schoolReadBatchRead(UEP_ADMISSIONS_FALLBACK_SPREADSHEET_ID'),'basic-info admissions fallback missing');
must(!m.includes('readSheetBatch(token,UEP_ADMISSIONS_SPREADSHEET_ID'),'legacy direct admissions read remains');
must(m.includes("'53B_전형유형별대학DB'!A1:S3000"),'53B A:S range missing');
must(m.includes("['52_대입기초"),'52 source missing');
must(m.includes("['56_대학입시마스터"),'56 source missing');
must(m.includes("['58_권장과목DB"),'58 source missing');
must(g.includes('수시(교과·종합)'),'early admission tab lost');
must(g.includes('수시(논술·기타)'),'other admission tab lost');
must(g.includes('>정시</label>'),'regular admission tab lost');
must(g.includes("importance(r)==='주요'"),'featured importance logic lost');
must(g.includes('지역의사제·주요 자격전형'),'featured restricted area lost');
must(g.includes('다른 전형 자세히 보기'),'detail disclosure lost');
must(g.includes("i.unavailable||(i.restricted&&!featured.includes(r))"),'restricted/unavailable detail rule lost');
console.log('0.82.60 admissions School Read migration/fallback regression test passed');
